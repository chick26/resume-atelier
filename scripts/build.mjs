import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const stylesheetOrder = [
  "workbench",
  "editor",
  "preview",
  "inspector",
  "responsive",
  "resume-paper",
  "resume-typography",
  "resume-variants",
  "markdown-elements",
  "printing",
  "icons",
];

const [javascript, styles] = await Promise.all([
  build({
    absWorkingDir: root,
    entryPoints: ["src/main.js"],
    bundle: true,
    external: ["obsidian"],
    format: "cjs",
    target: "es2021",
    loader: { ".md": "text" },
    banner: { js: "// Generated by npm run build. Edit src/ or examples/." },
    write: false,
  }),
  Promise.all(stylesheetOrder.map(name => readFile(new URL(`../src/styles/${name}.css`, import.meta.url), "utf8"))),
]);

const outputs = { "main.js": javascript.outputFiles[0].text, "styles.css": styles.join("\n") };
for (const [name, contents] of Object.entries(outputs)) {
  const file = new URL(`../${name}`, import.meta.url);
  if (check) {
    if (await readFile(file, "utf8") !== contents) throw new Error(`${name} is stale. Run npm run build.`);
  } else {
    await writeFile(file, contents);
  }
}
